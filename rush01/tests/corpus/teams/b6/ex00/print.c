#include "rush01.h"

void	ft_print(t_game *g)
{
	int		i;
	char	c;

	i = 0;
	while (i < 16)
	{
		c = g->grid[i] + '0';
		write(1, &c, 1);
		write(1, " ", 1);
		if (i % 4 == 3)
			write(1, "\n", 1);
		i++;
	}
}
