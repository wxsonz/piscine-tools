int	ft_vis(int *v, int rev)
{
	int	i;
	int	max;
	int	seen;

	i = 0;
	max = 0;
	seen = 0;
	while (i < 4)
	{
		if (v[3 * rev + i * (1 - 2 * rev)] > max)
		{
			max = v[3 * rev + i * (1 - 2 * rev)];
			seen++;
		}
		i++;
	}
	return (seen);
}
