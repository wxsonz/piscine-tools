#include "rush01.h"

int	ft_parse(char *s, t_game *g)
{
	int	i;
	int	ok;

	i = 0;
	ok = 1;
	while (i < 16)
	{
		g->clue[i / 4][i % 4] = s[i * 2] - '0';
		if (g->clue[i / 4][i % 4] < 1 || g->clue[i / 4][i % 4] > 4)
			ok = 0;
		if (i < 15 && s[i * 2 + 1] != ' ')
			ok = 0;
		i++;
	}
	return (ok && s[31] == '\0');
}
