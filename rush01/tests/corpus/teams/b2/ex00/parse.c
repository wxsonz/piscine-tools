#include "rush01.h"

int	ft_parse(char *s, t_game *g)
{
	int	i;

	i = 0;
	while (i < 16)
	{
		if (s[i * 2] < '1' || s[i * 2] > '4')
			return (0);
		if (i < 15 && s[i * 2 + 1] != ' ')
			return (0);
		g->clue[i / 4][i % 4] = s[i * 2] - '0';
		i++;
	}
	return (s[31] == '\0');
}
