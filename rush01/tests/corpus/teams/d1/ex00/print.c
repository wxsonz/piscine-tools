#include "rush01.h"

void	ft_print(t_game *g)
{
	int		i;
	char	c;

	i = 0;
	while (i < 16)
	{
		c = ' ';
		if (i % 4 == 3)
			c = '\n';
		printf("%d%c", g->grid[i], c);
		i++;
	}
}
